/**
 * Shared product card fragment used by the homepage grid, collections,
 * search results and recommendations.
 *
 * Merchandising content comes from metafields (see app/lib/content/metafields.ts):
 * - reviews.rating / reviews.rating_count (Shopify standard review metafields)
 * - mellow.badge ("BESTSELLER", "NEW")
 * - mellow.short_description (card copy)
 */
export const PRODUCT_CARD_FRAGMENT = `#graphql
  fragment MoneyProductCard on MoneyV2 {
    amount
    currencyCode
  }
  fragment ProductCard on Product {
    id
    handle
    title
    vendor
    availableForSale
    description
    featuredImage {
      id
      url
      altText
      width
      height
    }
    priceRange {
      minVariantPrice {
        ...MoneyProductCard
      }
      maxVariantPrice {
        ...MoneyProductCard
      }
    }
    compareAtPriceRange {
      minVariantPrice {
        ...MoneyProductCard
      }
      maxVariantPrice {
        ...MoneyProductCard
      }
    }
    badge: metafield(namespace: "mellow", key: "badge") {
      value
    }
    shortDescription: metafield(namespace: "mellow", key: "short_description") {
      value
    }
    rating: metafield(namespace: "reviews", key: "rating") {
      value
    }
    ratingCount: metafield(namespace: "reviews", key: "rating_count") {
      value
    }
  }
` as const;

const MENU_FRAGMENT = `#graphql
  fragment MenuItem on MenuItem {
    id
    resourceId
    tags
    title
    type
    url
  }
  fragment ChildMenuItem on MenuItem {
    ...MenuItem
  }
  fragment ParentMenuItem on MenuItem {
    ...MenuItem
    items {
      ...ChildMenuItem
    }
  }
  fragment Menu on Menu {
    id
    items {
      ...ParentMenuItem
    }
  }
` as const;

export const HEADER_QUERY = `#graphql
  fragment Shop on Shop {
    id
    name
    description
    primaryDomain {
      url
    }
    brand {
      logo {
        image {
          url
        }
      }
    }
  }
  query Header(
    $country: CountryCode
    $headerMenuHandle: String!
    $language: LanguageCode
  ) @inContext(language: $language, country: $country) {
    shop {
      ...Shop
    }
    menu(handle: $headerMenuHandle) {
      ...Menu
    }
  }
  ${MENU_FRAGMENT}
` as const;

